// Proof of One — reference tally implementation.
// Baby Jubjub group helpers (EIP-2494), wrapping circomlibjs.
//
// SECURITY ASSUMPTIONS
// - Decisional Diffie–Hellman is hard in the prime-order subgroup of Baby Jubjub.
// - Every point received from outside (ballots, keys, partial decryptions) MUST pass
//   isValidPoint(): on the curve AND in the prime-order subgroup. Baby Jubjub has
//   cofactor 8; skipping the subgroup check allows small-subgroup attacks.
// - Randomness comes from Node's CSPRNG (crypto.randomBytes).
// This is reference code for review and testing. It is NOT constant-time and must
// not be used to protect real participants.

"use strict";
const crypto = require("crypto");
const { buildBabyjub } = require("circomlibjs");

let bj = null;

async function init() {
  if (!bj) bj = await buildBabyjub();
  return api();
}

function api() {
  const F = bj.F;
  const L = bj.subOrder; // prime order ℓ of the subgroup generated by Base8
  const G = bj.Base8;
  const O = [F.zero, F.one]; // identity point of a twisted Edwards curve

  const mod = (a, m = L) => ((a % m) + m) % m;
  const add = (P, Q) => bj.addPoint(P, Q);
  const mul = (P, k) => bj.mulPointEscalar(P, mod(BigInt(k)));
  const neg = (P) => [F.neg(P[0]), P[1]];
  const sub = (P, Q) => add(P, neg(Q));
  const eq = (P, Q) => F.eq(P[0], Q[0]) && F.eq(P[1], Q[1]);
  const isValidPoint = (P) =>
    Array.isArray(P) && P.length === 2 && bj.inCurve(P) && bj.inSubgroup(P);

  // Uniform scalar in [1, ℓ-1]: 64 random bytes reduced mod ℓ (bias < 2^-250).
  function randScalar() {
    for (;;) {
      const r = mod(BigInt("0x" + crypto.randomBytes(64).toString("hex")));
      if (r !== 0n) return r;
    }
  }

  // Canonical external encoding: [x, y] as decimal strings.
  const toJSON = (P) => [F.toObject(P[0]).toString(), F.toObject(P[1]).toString()];
  const fromJSON = (a) => {
    const P = [F.e(BigInt(a[0])), F.e(BigInt(a[1]))];
    if (!isValidPoint(P)) throw new Error("invalid point: not on curve or not in subgroup");
    return P;
  };
  const coords = (P) => [F.toObject(P[0]), F.toObject(P[1])];
  const key = (P) => coords(P).join(",");

  return { F, L, G, O, mod, add, mul, neg, sub, eq, isValidPoint, randScalar, toJSON, fromJSON, coords, key };
}

module.exports = { init };
