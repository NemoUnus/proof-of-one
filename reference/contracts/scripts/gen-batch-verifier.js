"use strict";
const fs = require("fs");
const path = require("path");

const VK = path.join(__dirname, "..", "..", "ballot-circuit", "setup", "vkey_test.json");
const OUT = path.join(__dirname, "..", "src", "BallotBatchVerifier.sol");
const vk = JSON.parse(fs.readFileSync(VK, "utf8"));
if (vk.protocol !== "groth16" || vk.curve !== "bn128" || vk.nPublic !== 18) throw new Error("unexpected verification key");

// Precompile order for G2: x_im, x_re, y_im, y_re
const g2 = (p) => [p[0][1], p[0][0], p[1][1], p[1][0]];
const ic = vk.IC.flatMap((p) => [p[0], p[1]]);

const sol = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by scripts/gen-batch-verifier.js from ../ballot-circuit/setup/vkey_test.json.
// TEST-ONLY verification key. Do NOT deploy. Reference code; not audited.
pragma solidity ^0.8.24;

/// @title Batched Groth16 verification of ballot proofs π_vote
/// @notice Verifies n ballot proofs of the same poll with n + 3 pairings instead of 4n.
///         Each proof i must satisfy  e(A_i, B_i) = e(α, β) · e(X_i, γ) · e(C_i, δ),
///         where X_i = IC_0 + Σ_j x_ij · IC_{j+1}. With random weights r_i the batch checks
///           Π e(−r_i·A_i, B_i) · e((Σ r_i)·α, β) · e(Σ r_i·X_i, γ) · e(Σ r_i·C_i, δ) = 1.
///         If any single proof is invalid, the batch passes with probability at most
///         about 2^-128 for weights drawn after the proofs are fixed (small-exponent
///         batch verification, Bellare–Garay–Rabin 1998). The weights are derived by
///         hashing the complete call data, so they are fixed only after every proof and
///         public input is.
/// @dev Σ r_i·X_i is computed with scalar arithmetic first, so the 19 multiplications by
///      IC points are paid once per batch, not once per proof. Public inputs per ballot:
///      [pollHash, nf, A_0..A_3 (x, y), B_0..B_3 (x, y)], identical to Groth16Verifier.
contract BallotBatchVerifier {
    uint256 internal constant R = 21888242871839275222246405745257275088548364400416034343698204186575808495617;
    uint256 internal constant Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583;
    uint256 public constant MAX_BATCH = 256;
    // A failing precompile call consumes all gas forwarded to it, so each call gets a
    // fixed allowance above its EIP-1108 price. An invalid point then makes the batch
    // return false instead of exhausting the caller's gas.
    uint256 internal constant MUL_GAS = 10000; // ecMul: 6,000
    uint256 internal constant ADD_GAS = 1000;  // ecAdd: 150

    uint256 internal constant ALPHA_X = ${vk.vk_alpha_1[0]};
    uint256 internal constant ALPHA_Y = ${vk.vk_alpha_1[1]};
${["BETA", "GAMMA", "DELTA"].map((n, k) => g2([vk.vk_beta_2, vk.vk_gamma_2, vk.vk_delta_2][k]).map((v, i) => `    uint256 internal constant ${n}_${i} = ${v};`).join("\n")).join("\n")}

    struct Proof { uint256[2] a; uint256[2][2] b; uint256[2] c; }

    function _ic() internal pure returns (uint256[${ic.length}] memory) {
        return [
${ic.map((v) => `            uint256(${v})`).join(",\n")}
        ];
    }

    /// @notice True if every proof verifies for its ballot under the given poll hash.
    function verifyBallots(
        uint256 pollHash,
        uint256[] calldata nfs,
        uint256[16][] calldata cts,
        Proof[] calldata proofs
    ) external view returns (bool) {
        uint256 n = proofs.length;
        if (n == 0 || n > MAX_BATCH || nfs.length != n || cts.length != n) return false;
        if (pollHash >= R) return false;

        bytes32 seed = keccak256(msg.data);
        uint256[18] memory s;          // Σ_i r_i · x_ij  for each public input j
        uint256 sumR;
        uint256[2] memory accC;        // Σ_i r_i · C_i
        bytes memory pairs = new bytes(192 * (n + 3));
        bool ok = true;

        for (uint256 i = 0; i < n; i++) {
            uint256 r = (uint256(keccak256(abi.encodePacked(seed, i))) >> 128) | 1;
            sumR = addmod(sumR, r, R);
            uint256 nf = nfs[i];
            if (nf >= R) return false;
            s[1] = addmod(s[1], mulmod(r, nf, R), R);
            for (uint256 k = 0; k < 16; k++) {
                uint256 x = cts[i][k];
                if (x >= R) return false;
                s[2 + k] = addmod(s[2 + k], mulmod(r, x, R), R);
            }
            Proof calldata p = proofs[i];
            (bool okA, uint256 ax, uint256 ay) = _mul(p.a[0], p.a[1], r);
            (bool okC, uint256 cx, uint256 cy) = _mul(p.c[0], p.c[1], r);
            bool okS;
            (okS, accC[0], accC[1]) = _add(accC[0], accC[1], cx, cy);
            ok = ok && okA && okC && okS;
            uint256 off = 192 * i;
            uint256 nay = ay == 0 ? 0 : Q - ay;
            uint256 b00 = p.b[0][0]; uint256 b01 = p.b[0][1]; uint256 b10 = p.b[1][0]; uint256 b11 = p.b[1][1];
            assembly ("memory-safe") {
                let d := add(add(pairs, 32), off)
                mstore(d, ax)
                mstore(add(d, 32), nay)
                mstore(add(d, 64), b00)
                mstore(add(d, 96), b01)
                mstore(add(d, 128), b10)
                mstore(add(d, 160), b11)
            }
        }
        if (!ok) return false;
        s[0] = mulmod(pollHash, sumR, R);

        // X = (Σ r_i)·IC_0 + Σ_j s_j·IC_{j+1}
        uint256[${ic.length}] memory ic = _ic();
        (bool okX, uint256 xx, uint256 xy) = _mul(ic[0], ic[1], sumR);
        for (uint256 j = 0; j < 18; j++) {
            (bool m1, uint256 px, uint256 py) = _mul(ic[2 * j + 2], ic[2 * j + 3], s[j]);
            bool m2;
            (m2, xx, xy) = _add(xx, xy, px, py);
            okX = okX && m1 && m2;
        }
        (bool okAl, uint256 alx, uint256 aly) = _mul(ALPHA_X, ALPHA_Y, sumR);
        if (!okX || !okAl) return false;

        uint256 base = 192 * n;
        uint256[18] memory tail = [
            alx, aly, BETA_0, BETA_1, BETA_2, BETA_3,
            xx, xy, GAMMA_0, GAMMA_1, GAMMA_2, GAMMA_3,
            accC[0], accC[1], DELTA_0, DELTA_1, DELTA_2, DELTA_3
        ];
        for (uint256 k = 0; k < 18; k++) {
            uint256 v = tail[k];
            assembly ("memory-safe") { mstore(add(add(add(pairs, 32), base), mul(k, 32)), v) }
        }
        uint256 len = pairs.length;
        uint256 pairingGas = 45000 + 34000 * (n + 3) + 10000;
        uint256[1] memory out;
        bool success;
        assembly ("memory-safe") { success := staticcall(pairingGas, 8, add(pairs, 32), len, out, 32) }
        return success && out[0] == 1;
    }

    function _mul(uint256 x, uint256 y, uint256 k) internal view returns (bool ok, uint256 rx, uint256 ry) {
        uint256[3] memory input = [x, y, k];
        uint256[2] memory out;
        assembly ("memory-safe") { ok := staticcall(MUL_GAS, 7, input, 96, out, 64) }
        return (ok, out[0], out[1]);
    }

    function _add(uint256 x1, uint256 y1, uint256 x2, uint256 y2) internal view returns (bool ok, uint256 rx, uint256 ry) {
        uint256[4] memory input = [x1, y1, x2, y2];
        uint256[2] memory out;
        assembly ("memory-safe") { ok := staticcall(ADD_GAS, 6, input, 128, out, 64) }
        return (ok, out[0], out[1]);
    }
}
`;
fs.writeFileSync(OUT, sol);
console.log("wrote", path.relative(process.cwd(), OUT));
